/**
 * Google Flow - REAL text-to-video pipeline (runs INSIDE a worker node)
 * =====================================================================
 *   Stage 1  prompt  -> styled prompt                      (Java)
 *   Stage 2  prompt  -> REAL AI image via a free API       (Pollinations, or Hugging Face FLUX)
 *   Stage 3  image   -> "video": a virtual camera (static / pan / tilt / zoom) moves over the
 *                       AI image; frames are encoded into a looping animated GIF (Java only)
 *
 * Free text-to-video models with true motion are not available without payment, so the motion
 * comes from the camera move while the picture itself is generated by AI from the prompt.
 *
 * If no AI service can be reached and FLOW_FALLBACK=true (default), the old simulated pixel
 * animation is produced instead (clearly labelled), so the demo never breaks.
 *
 * Settings (env var or server/config.properties) - see config.properties.
 */
public class AiPipeline {

    public static class GenerationException extends Exception {
        public GenerationException(String m) { super(m); }
    }

    private static final Random RAND = new Random();

    // ------------------------------------------------------------ settings --
    static final String PROVIDER      = Config.get("FLOW_PROVIDER", "pollinations").toLowerCase(); // pollinations | huggingface | simulated
    static final String POLLI_BASE    = Config.get("POLLINATIONS_BASE", "https://image.pollinations.ai/prompt");
    static final String POLLI_MODEL   = Config.get("POLLINATIONS_MODEL", "flux");
    static final String HF_TOKEN      = Config.get("HF_TOKEN", "");
    static final String HF_URL_BASE   = Config.get("HF_URL_BASE", "https://router.huggingface.co/hf-inference/models");
    static final String HF_MODEL      = Config.get("HF_MODEL", "black-forest-labs/FLUX.1-schnell");
    static final long   MIN_GAP_MS    = Config.getInt("FLOW_MIN_GAP_MS", 15000);   // Pollinations anonymous tier: ~1 request / 15 s
    static final boolean FALLBACK     = Config.getBool("FLOW_FALLBACK", false);   // false = failed jobs are retried, then marked Failed + quota refunded
    static final int    MAX_TRIES     = Config.getInt("FLOW_API_TRIES", 5);        // attempts per image request
    static final long   RETRY_WAIT_MS = Config.getInt("FLOW_RETRY_WAIT_MS", 10000); // extra wait after a failed attempt (x attempt number)

    private static final HttpClient HTTP = HttpClient.newBuilder()
            .followRedirects(HttpClient.Redirect.NORMAL)
            .connectTimeout(Duration.ofSeconds(15)).build();

    // --------------------------------------------------------------- entry --
    /** Returns {gifBytes, durationSeconds}. Throws GenerationException so the backend can retry / fail over. */
    public static Object[] generateClip(String promptText, String style, String camera, String aspect,
                                        String model, double failProbability) throws Exception {
        boolean quality = "quality".equalsIgnoreCase(model);
        boolean portrait = "9:16".equals(aspect);
        String st = style == null ? "realistic" : style.toLowerCase();
        String cam = camera == null ? "static" : camera.toLowerCase();

        int outW = portrait ? 270 : 480, outH = portrait ? 480 : 270;     // same clip size as before
        int srcW = quality ? 1024 : 768, srcH = quality ? 576 : 432;      // size asked from the AI (multiples of 16)
        if (portrait) { int t = srcW; srcW = srcH; srcH = t; }
        int unique = quality ? 20 : 14;                                   // frames of one camera sweep (played forward + back)
        int delayCs = 8;

        if (failProbability > 0 && RAND.nextDouble() < failProbability)
            throw new GenerationException("Simulated transient failure (FLOW_FAIL_PROB)");

        Object[] got = fetchBaseImage(promptText, st, srcW, srcH);       // Stages 1 + 2
        BufferedImage base = (BufferedImage) got[0];
        String used = (String) got[1], lastError = (String) got[2];

        List<BufferedImage> frames = new ArrayList<>();
        if (base != null) {                                               // Stage 3
            System.out.println("[ai] image from " + used + " (" + base.getWidth() + "x" + base.getHeight()
                    + "), camera=" + cam + ", " + quality(quality));
            frames = cameraFrames(base, cam, unique, outW, outH);
        } else if (FALLBACK) {
            System.out.println("[ai] !!! no AI service reachable (" + lastError + ") -> OFFLINE DEMO animation. "
                    + "Check your internet / config.properties.");
            for (int i = 0; i < 10; i++) frames.add(simulatedFrame(promptText, st, cam, i, 10, outW, outH));
        } else {
            throw new GenerationException(lastError == null ? "No AI provider configured" : lastError);
        }

        File tmp = File.createTempFile("flow_", ".gif");
        try {
            AnimatedGifWriter gif = new AnimatedGifWriter(tmp, delayCs);
            for (BufferedImage f : frames) gif.addFrame(f);
            gif.close();
            byte[] bytes = java.nio.file.Files.readAllBytes(tmp.toPath());
            double duration = Math.round(frames.size() * delayCs) / 100.0;
            System.out.println("[ai] clip ready: " + frames.size() + " frames, " + bytes.length / 1024 + " KB");
            return new Object[]{bytes, duration};
        } finally {
            tmp.delete();
        }
    }

    // ------------------------------------------------- TEXT -> IMAGE (new) ---
    /**
     * Text -> Image. Runs inside a worker node for the "generate_image" command.
     * Stage 1: styled prompt, Stage 2: REAL AI image from the free API (same providers, same rate-limit
     * queue as video), Stage 3: re-encode as PNG. Returns {pngBytes, width, height}.
     * Throws GenerationException so the backend can retry / fail over, exactly like for video.
     */
    public static Object[] generateImage(String promptText, String style, String aspect,
                                         String model, double failProbability) throws Exception {
        boolean quality = "quality".equalsIgnoreCase(model);
        String st = style == null ? "realistic" : style.toLowerCase();
        int w, h;                                                          // multiples of 16, as asked from the AI
        if ("1:1".equals(aspect))      { w = quality ? 1024 : 704; h = w; }
        else if ("9:16".equals(aspect)) { w = quality ? 576 : 432;  h = quality ? 1024 : 768; }
        else                            { w = quality ? 1024 : 768; h = quality ? 576 : 432; }

        if (failProbability > 0 && RAND.nextDouble() < failProbability)
            throw new GenerationException("Simulated transient failure (FLOW_FAIL_PROB)");

        Object[] got = fetchBaseImage(promptText, st, w, h);
        BufferedImage img = (BufferedImage) got[0];
        String used = (String) got[1], lastError = (String) got[2];
        if (img != null) {
            System.out.println("[ai] image from " + used + " (" + img.getWidth() + "x" + img.getHeight() + "), "
                    + (quality ? "Quality" : "Fast"));
        } else if (FALLBACK) {
            System.out.println("[ai] !!! no AI service reachable (" + lastError + ") -> OFFLINE DEMO image.");
            img = simulatedFrame(promptText, st, "static", 0, 1, w, h);
        } else {
            throw new GenerationException(lastError == null ? "No AI provider configured" : lastError);
        }
        try {
            BufferedImage rgb = new BufferedImage(img.getWidth(), img.getHeight(), BufferedImage.TYPE_INT_RGB);
            Graphics2D g = rgb.createGraphics();
            g.drawImage(img, 0, 0, null);                                  // flatten (drops alpha) so PNG is always valid
            g.dispose();
            java.io.ByteArrayOutputStream bos = new java.io.ByteArrayOutputStream();
            ImageIO.write(rgb, "png", bos);
            byte[] bytes = bos.toByteArray();
            System.out.println("[ai] image ready: " + rgb.getWidth() + "x" + rgb.getHeight() + ", " + bytes.length / 1024 + " KB");
            return new Object[]{bytes, rgb.getWidth(), rgb.getHeight()};
        } catch (java.io.IOException e) {
            throw new GenerationException("PNG encoding failed: " + e);
        }
    }

    /** Stages 1+2 shared by video and image: styled prompt -> picture from the first provider that works. */
    private static Object[] fetchBaseImage(String promptText, String st, int w, int h) {
        BufferedImage base = null;
        String used = null, lastError = null;
        if (!PROVIDER.equals("simulated")) {
            String styled = stylePrompt(promptText, st);                  // Stage 1
            List<String> order = new ArrayList<>(PROVIDER.equals("huggingface")
                    ? List.of("huggingface", "pollinations") : List.of("pollinations", "huggingface"));
            if (HF_TOKEN.isBlank()) order.remove("huggingface");
            for (String p : order) {                                      // Stage 2
                try {
                    base = p.equals("pollinations") ? fetchPollinations(styled, w, h) : fetchHuggingFace(styled, w, h);
                    used = p;
                    break;
                } catch (GenerationException e) {
                    lastError = e.getMessage();
                    System.out.println("[ai] " + p + " failed: " + lastError);
                }
            }
        }
        return new Object[]{base, used, lastError};
    }

    private static String quality(boolean q) { return q ? "Veo Quality (1024px source)" : "Veo Fast (768px source)"; }

    // ------------------------------------------------------------ stage 1 ---
    private static String stylePrompt(String prompt, String style) {
        String p = prompt == null ? "" : prompt.trim();
        if (p.length() > 450) p = p.substring(p.length() - 450);          // keep the newest part (Extend adds text at the end)
        switch (style) {
            case "cartoon":   return p + ", colorful cartoon illustration, flat shading, vibrant colors";
            case "cinematic": return p + ", cinematic film still, dramatic lighting, shallow depth of field, 35mm";
            case "realistic": return p + ", photorealistic, natural lighting, highly detailed";
            case "anime":     return p + ", anime style illustration, clean line art, vivid colors";
            case "painting":  return p + ", digital oil painting, visible brush strokes, rich textures";
            case "3d":        return p + ", 3D render, soft studio lighting, smooth materials, octane render";
            default:          return p;
        }
    }

    // ------------------------------------------------------------ stage 2 ---
    // Pollinations' free tier allows about one request per 15 s per IP. All nodes in this JVM share
    // one queue of "time slots" so parallel jobs wait their turn instead of being rejected (HTTP 429).
    private static final Object LIMIT = new Object();
    private static long nextSlot = 0;

    private static void throttle(long gapMs) throws InterruptedException {
        long wait;
        synchronized (LIMIT) {
            long now = System.currentTimeMillis();
            long slot = Math.max(now, nextSlot);
            nextSlot = slot + gapMs;
            wait = slot - now;
        }
        if (wait > 0) {
            System.out.println("[ai] waiting " + wait / 1000 + "s for a free API slot (free-tier rate limit)");
            Thread.sleep(wait);
        }
    }

    private static BufferedImage fetchPollinations(String prompt, int w, int h) throws GenerationException {
        String url = POLLI_BASE + "/" + URLEncoder.encode(prompt, StandardCharsets.UTF_8).replace("+", "%20")
                + "?width=" + w + "&height=" + h + "&model=" + POLLI_MODEL
                + "&seed=" + RAND.nextInt(1_000_000) + "&nologo=true";
        String last = "unknown error";
        for (int attempt = 1; attempt <= MAX_TRIES; attempt++) {
            try {
                throttle(MIN_GAP_MS);
                HttpRequest req = HttpRequest.newBuilder(URI.create(url)).timeout(Duration.ofSeconds(120))
                        .header("User-Agent", "GoogleFlowJava/1.0").GET().build();
                HttpResponse<byte[]> r = HTTP.send(req, HttpResponse.BodyHandlers.ofByteArray());
                int code = r.statusCode();
                if (code == 200) return decode(r.body(), r.headers().firstValue("content-type").orElse("?"));
                last = "Pollinations HTTP " + code;
                // 402 / 429 / 5xx on the free tier are usually temporary (busy or quota window) -> wait and retry
                boolean retryable = code == 402 || code == 408 || code == 429 || code >= 500;
                if (!retryable) throw new GenerationException(last);
            } catch (GenerationException e) {
                throw e;
            } catch (InterruptedException e) {
                Thread.currentThread().interrupt();
                throw new GenerationException("Interrupted");
            } catch (Exception e) {
                last = "Pollinations network error: " + e;
            }
            if (attempt < MAX_TRIES) {
                long wait = RETRY_WAIT_MS * attempt;
                System.out.println("[ai] " + last + " (attempt " + attempt + "/" + MAX_TRIES + ") - retrying in " + wait / 1000 + "s");
                try { Thread.sleep(wait); } catch (InterruptedException e) { Thread.currentThread().interrupt(); throw new GenerationException("Interrupted"); }
            }
        }
        throw new GenerationException(last + " (gave up after " + MAX_TRIES + " attempts)");
    }

    private static BufferedImage fetchHuggingFace(String prompt, int w, int h) throws GenerationException {
        try {
            Map<String, Object> params = new LinkedHashMap<>();
            params.put("width", w); params.put("height", h);
            Map<String, Object> body = new LinkedHashMap<>();
            body.put("inputs", prompt); body.put("parameters", params);
            HttpRequest req = HttpRequest.newBuilder(URI.create(HF_URL_BASE + "/" + HF_MODEL))
                    .timeout(Duration.ofSeconds(120))
                    .header("Authorization", "Bearer " + HF_TOKEN)
                    .header("Content-Type", "application/json")
                    .POST(HttpRequest.BodyPublishers.ofString(Json.stringify(body))).build();
            HttpResponse<byte[]> r = HTTP.send(req, HttpResponse.BodyHandlers.ofByteArray());
            if (r.statusCode() == 200) return decode(r.body(), r.headers().firstValue("content-type").orElse("?"));
            String msg = new String(r.body(), StandardCharsets.UTF_8);
            throw new GenerationException("HuggingFace HTTP " + r.statusCode() + ": "
                    + msg.substring(0, Math.min(160, msg.length())));
        } catch (GenerationException e) {
            throw e;
        } catch (Exception e) {
            throw new GenerationException("HuggingFace network error: " + e);
        }
    }

    private static BufferedImage decode(byte[] data, String contentType) throws GenerationException {
        try {
            BufferedImage img = ImageIO.read(new ByteArrayInputStream(data));
            if (img != null) return img;
        } catch (Exception ignored) { }
        String peek = new String(data, 0, Math.min(120, data.length), StandardCharsets.UTF_8).replaceAll("\\s+", " ");
        throw new GenerationException("Service did not return a readable image (" + contentType + "): " + peek);
    }

    // ------------------------------------------------------------ stage 3 ---
    /** Virtual camera over the AI image. Frames go forward then backward so the looping GIF is seamless. */
    private static List<BufferedImage> cameraFrames(BufferedImage src, String cam, int unique, int outW, int outH) {
        double sw = src.getWidth(), sh = src.getHeight(), aspect = (double) outW / outH;
        double baseW, baseH;                                              // biggest window with the output aspect ratio
        if (sw / sh > aspect) { baseH = sh; baseW = sh * aspect; } else { baseW = sw; baseH = sw / aspect; }
        double offX = (sw - baseW) / 2, offY = (sh - baseH) / 2;

        List<Double> ts = new ArrayList<>();
        for (int i = 0; i < unique; i++) ts.add(i / (double) (unique - 1));
        for (int i = unique - 2; i >= 1; i--) ts.add(i / (double) (unique - 1));

        List<BufferedImage> frames = new ArrayList<>();
        for (double t : ts) {
            double e = t * t * (3 - 2 * t);                               // smoothstep easing
            double z = 1.0, fx = 0.5, fy = 0.5;
            switch (cam) {
                case "pan":  z = 1.30; fx = e; break;                     // left -> right
                case "tilt": z = 1.35; fy = e; break;                     // top -> bottom
                case "zoom": z = 1.0 + 0.6 * e; break;                    // push in
                default:     z = 1.05 + 0.05 * e;                         // static: very gentle drift
            }
            double cw = baseW / z, ch = baseH / z;
            double cx = offX + fx * (baseW - cw), cy = offY + fy * (baseH - ch);
            double s = outW / cw;

            BufferedImage out = new BufferedImage(outW, outH, BufferedImage.TYPE_INT_RGB);
            Graphics2D g = out.createGraphics();
            g.setRenderingHint(RenderingHints.KEY_INTERPOLATION, RenderingHints.VALUE_INTERPOLATION_BICUBIC);
            g.setRenderingHint(RenderingHints.KEY_RENDERING, RenderingHints.VALUE_RENDER_QUALITY);
            g.setColor(Color.BLACK);
            g.fillRect(0, 0, outW, outH);
            AffineTransform at = new AffineTransform();
            at.scale(s, s);
            at.translate(-cx, -cy);
            g.drawImage(src, at, null);
            g.dispose();
            frames.add(out);
        }
        return frames;
    }

    // ------------------------------------------------- offline demo fallback ---
    private static final Map<String, Color[]> STYLE_COLORS = new HashMap<>();
    static {
        STYLE_COLORS.put("realistic", new Color[]{new Color(40, 40, 40), new Color(95, 95, 95)});
        STYLE_COLORS.put("cartoon", new Color[]{new Color(255, 145, 0), new Color(255, 205, 60)});
        STYLE_COLORS.put("cinematic", new Color[]{new Color(10, 15, 40), new Color(70, 25, 95)});
        STYLE_COLORS.put("default", new Color[]{new Color(20, 60, 110), new Color(40, 130, 205)});
    }

    private static BufferedImage simulatedFrame(String prompt, String style, String camera,
                                                int index, int total, int W, int H) {
        Color[] colors = STYLE_COLORS.getOrDefault(style, STYLE_COLORS.get("default"));
        double t = (double) index / Math.max(total - 1, 1);
        Color bg = lerp(colors[0], colors[1], t);

        BufferedImage img = new BufferedImage(W, H, BufferedImage.TYPE_INT_RGB);
        Graphics2D g = img.createGraphics();
        g.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
        g.setColor(bg);
        g.fillRect(0, 0, W, H);

        int cx = W / 2, cy = H / 2, r = 25;
        switch (camera) {
            case "pan":  cx = (int) (30 + t * (W - 60)); break;
            case "tilt": cy = (int) (50 + t * (H - 100)); break;
            case "zoom": r = (int) (12 + t * 55); break;
            default:     r = (int) (25 + 6 * Math.sin(t * Math.PI * 2));
        }
        g.setColor(lerp(bg, Color.WHITE, 0.4));
        g.fillOval(cx - r, cy - r, 2 * r, 2 * r);

        g.setColor(Color.WHITE);
        g.setFont(new Font("SansSerif", Font.BOLD, 14));
        g.drawString("OFFLINE DEMO [" + style + "]", 12, 22);
        g.setFont(new Font("SansSerif", Font.PLAIN, 13));
        drawWrapped(g, prompt, 12, 40, W - 24, H);
        g.setFont(new Font("SansSerif", Font.PLAIN, 11));
        g.drawString("AI service unreachable - simulated frame " + (index + 1) + "/" + total, 12, H - 12);
        g.dispose();
        return img;
    }

    private static void drawWrapped(Graphics2D g, String text, int x, int y, int width, int H) {
        if (text == null || text.isEmpty()) return;
        AttributedString attr = new AttributedString(text);
        attr.addAttribute(TextAttribute.FONT, g.getFont());
        FontRenderContext frc = g.getFontRenderContext();
        LineBreakMeasurer measurer = new LineBreakMeasurer(attr.getIterator(), frc);
        int curY = y;
        while (measurer.getPosition() < text.length()) {
            var layout = measurer.nextLayout(width);
            curY += layout.getAscent();
            layout.draw(g, x, curY);
            curY += layout.getDescent() + layout.getLeading();
            if (curY > H - 20) break;
        }
    }

    private static Color lerp(Color a, Color b, double t) {
        return new Color(
                (int) (a.getRed() + (b.getRed() - a.getRed()) * t),
                (int) (a.getGreen() + (b.getGreen() - a.getGreen()) * t),
                (int) (a.getBlue() + (b.getBlue() - a.getBlue()) * t));
    }
}
